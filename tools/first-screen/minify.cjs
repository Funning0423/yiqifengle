#!/usr/bin/env node
'use strict';
// Readable source: tools/first-screen/src/first-screen.js. Creator copies build-templates/wechatgame/ verbatim, so the
// shipped file is this committed minified copy. Regenerate after every source edit:  node tools/first-screen/minify.cjs
// (--check: exit 1 if the committed copy is not built from the current source). Terser: QF_TERSER or /workspace/wt/terser.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const ROOT=path.resolve(__dirname,'../..'),SRC=path.join(__dirname,'src/first-screen.js'),OUT=path.join(ROOT,'creator-build-project/build-templates/wechatgame/first-screen.js');
const sha=b=>crypto.createHash('sha256').update(b).digest('hex');
const header=s=>'/* first-screen.js — GENERATED by tools/first-screen/minify.cjs from tools/first-screen/src/first-screen.js sha256='+s+'. Edit the source. */\n';
function srcSha(){return sha(fs.readFileSync(SRC));}
function committedSha(){const m=/sha256=([0-9a-f]{64})/.exec(fs.readFileSync(OUT,'utf8').slice(0,400));return m?m[1]:null;}
module.exports={SRC,OUT,srcSha,committedSha};
if(require.main===module){
  if(process.argv.includes('--check')){const ok=committedSha()===srcSha();console.log(ok?'first-screen minified copy is current':'STALE: run node tools/first-screen/minify.cjs');process.exit(ok?0:1);}
  const terser=require(process.env.QF_TERSER||'/workspace/wt/terser/node_modules/terser');
  terser.minify(fs.readFileSync(SRC,'utf8'),{ecma:5,compress:{passes:2},mangle:true,format:{ascii_only:false,comments:false}}).then(r=>{
    fs.writeFileSync(OUT,header(srcSha())+r.code+'\n');console.log('wrote',path.relative(ROOT,OUT),fs.statSync(OUT).size,'B from',fs.statSync(SRC).size,'B');});
}
