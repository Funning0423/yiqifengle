'use strict';
const assert=require('node:assert/strict');
const {load}=require('./load.cjs');
const I=load('world-r2/ExploreInput.ts');
const G=load('region/ExploreGate.ts');
const M=load('ui/NodeMarkers.ts');
G.setExploreEnabled(false);
assert.equal(I.worldClosed(),true);
assert.equal(I.classifyPointers({uiHit:false,pointers:1,movedPt:0,heldS:0.1,boardOpen:true,blending:false,explore:true}),'ignored');
G.setExploreEnabled(true);
assert.equal(I.classifyPointers({uiHit:true,pointers:2,movedPt:40,heldS:1,boardOpen:false,blending:false,explore:true}),'ui');
assert.equal(I.classifyPointers({uiHit:false,pointers:2,movedPt:0,heldS:0.1,boardOpen:false,blending:false,explore:true}),'pinch');
assert.equal(I.classifyPointers({uiHit:false,pointers:1,movedPt:10,heldS:0.4,boardOpen:false,blending:false,explore:true}),'drag');
assert.equal(I.classifyPointers({uiHit:false,pointers:1,movedPt:9.9,heldS:0.25,boardOpen:false,blending:false,explore:true}),'tap');
assert.equal(I.classifyPointers({uiHit:false,pointers:1,movedPt:0,heldS:0.1,boardOpen:false,blending:true,explore:true}),'swallowed');
assert.equal(I.classifyPointers({uiHit:false,pointers:1,movedPt:20,heldS:0.2,boardOpen:false,blending:false,explore:false}),'ignored');
assert.equal(JSON.stringify(I.resolveTap({nodeId:'M3',nodePhase:'locked',propId:null,groundM:1,explore:false})),JSON.stringify({kind:'locked',id:'M3',walk:false,feedback:'shake'}));
assert.equal(I.resolveTap({nodeId:'M3',nodePhase:'playable',propId:'bell',groundM:1,explore:false}).walk,true);
assert.equal(I.resolveTap({nodeId:null,propId:'bell',groundM:1,explore:false}).kind,'prop');
assert.equal(I.resolveTap({nodeId:null,propId:null,groundM:3,explore:true}).kind,'ground');
assert.equal(I.resolveTap({nodeId:null,propId:null,groundM:3.01,explore:true}),null);
assert.equal(I.pickMarker([{id:'a',distancePt:20,toGirl:10},{id:'b',distancePt:30,toGirl:4}]),'b');
for(const region of ['island','meadow','skycity'])assert.ok(I.SCENE_PROPS[region].length>=4&&I.SCENE_PROPS[region].length<=6);
const fb=I.propFeedback('windmill');assert.ok(fb.seconds>=0.3&&fb.seconds<=0.6);
assert.equal(M.ROUTE_HINT_DC,1);
assert.ok(M.footprints([0,0,0],[20,0,0]).length<=M.ROUTE_MAX);
assert.equal(M.markerDraw('passed',0,false).fill,'#e2b657');
assert.ok(Math.abs(M.markerDraw('playable',0.4,false).scale-1)<=0.041);
assert.equal(M.markerDraw('locked',0,true).opacity,0.4);
assert.equal(M.routeHintVisible('Board',false,true),false);
assert.equal(M.routeHintVisible('MapExplore',true,false),true);
assert.equal(M.routeHintVisible('FollowWalk',false,true),true);
assert.equal(M.exploreHint(false),'这里可以随意走走了');
assert.equal(M.recenterButton().sizePt,44);
console.log('explore-input PASS');
