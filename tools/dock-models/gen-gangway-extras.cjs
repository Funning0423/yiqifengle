#!/usr/bin/env node
/** cand7: extract sail_gangway_hinge glTF extras from sailboat.glb into SailGangwayExtras.ts (Creator drops node extras at import).
 *  node tools/dock-models/gen-gangway-extras.cjs [--check] */
const fs=require('fs'),path=require('path'),crypto=require('crypto');
const root=path.resolve(__dirname,'../..');
const glb=path.join(root,'creator-build-project/assets/bundles/transport_sail/sailboat.glb');
const out=path.join(root,'creator-build-project/assets/scripts/region/SailGangwayExtras.ts');
function read(){const b=fs.readFileSync(glb),len=b.readUInt32LE(12),j=JSON.parse(b.slice(20,20+len).toString('utf8'));
 const n=(j.nodes||[]).find(x=>x.name==='sail_gangway_hinge');return {sha:crypto.createHash('sha256').update(b).digest('hex'),node:n||null};}
function render(r){const e=r.node&&r.node.extras?r.node.extras:null;const t=r.node&&r.node.translation||null;
 return '/** Generated by tools/dock-models/gen-gangway-extras.cjs from sailboat.glb (sha256 '+r.sha+'). Do not edit by hand. Pure data, no cc. */\n'+
 'export const SAIL_GANGWAY_GLB_SHA256='+JSON.stringify(r.sha)+';\n'+
 'export const SAIL_GANGWAY_EXTRAS:Readonly<Record<string,unknown>>|null='+(e?JSON.stringify({...e,meadowHinge:t}):'null')+';\n';}
module.exports={read,render,out};
if(require.main===module){const s=render(read());
 if(process.argv.includes('--check')){const cur=fs.existsSync(out)?fs.readFileSync(out,'utf8'):'';if(cur!==s){console.error('FAIL SailGangwayExtras.ts stale; re-run gen-gangway-extras.cjs');process.exit(1);}console.log('PASS SailGangwayExtras.ts matches sailboat.glb');}
 else{fs.writeFileSync(out,s);console.log('wrote',path.relative(root,out));}}
